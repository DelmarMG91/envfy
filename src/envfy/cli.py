"""Command line interface for envfy."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import List, Optional, Sequence

from . import __version__
from .diff import DiffResult, compare, format_diff
from .parser import EnvParseError, load_env
from .validator import (
    Report,
    SchemaError,
    check,
    infer_schema,
    load_schema,
    render_schema,
)

PROG = "envfy"

_MARKS = {"ok": "✓", "error": "✗", "warning": "!"}
_ASCII_FALLBACK = {"✓": "OK", "✗": "X"}


def build_parser() -> argparse.ArgumentParser:
    """Build the argparse parser used by the ``envfy`` entry point."""

    parser = argparse.ArgumentParser(
        prog=PROG,
        description="Validate and diff .env files against a schema.",
        epilog=(
            "examples:\n"
            "  envfy check --env .env --schema .env.schema\n"
            "  envfy diff .env .env.example\n"
            "  envfy init --env .env.example --output .env.schema\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
        help="print the envfy version and exit",
    )

    subparsers = parser.add_subparsers(dest="command", required=True, metavar="COMMAND")

    check_parser = subparsers.add_parser(
        "check",
        help="validate a .env file against a schema",
        description="Validate missing, extra, malformed and empty values in a .env file.",
    )
    check_parser.add_argument("--env", default=".env", help="path to the .env file (default: .env)")
    check_parser.add_argument(
        "--schema", default=".env.schema", help="path to the schema file (default: .env.schema)"
    )
    check_parser.add_argument(
        "--allow-extra",
        action="store_true",
        help="do not warn about keys that are absent from the schema",
    )
    check_parser.add_argument("--json", action="store_true", help="emit a machine-readable JSON report")
    check_parser.set_defaults(handler=_cmd_check)

    diff_parser = subparsers.add_parser(
        "diff",
        help="compare two .env files",
        description="Report keys only in A, only in B and keys whose values differ (values are hidden).",
    )
    diff_parser.add_argument("a", metavar="A", help="first .env file")
    diff_parser.add_argument("b", metavar="B", help="second .env file")
    diff_parser.add_argument("--json", action="store_true", help="emit a machine-readable JSON report")
    diff_parser.set_defaults(handler=_cmd_diff)

    init_parser = subparsers.add_parser(
        "init",
        help="infer a schema from an example .env file",
        description="Generate a .env.schema from an example file: filled values become string, empty values become required.",
    )
    init_parser.add_argument(
        "--env", default=".env.example", help="path to the example .env file (default: .env.example)"
    )
    init_parser.add_argument(
        "--output", default=".env.schema", help="path of the schema to write (default: .env.schema)"
    )
    init_parser.set_defaults(handler=_cmd_init)

    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Run the CLI and return a process exit code (0 ok, 1 findings, 2 error)."""

    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return int(args.handler(args))
    except (EnvParseError, SchemaError) as exc:
        print(f"{PROG}: error: {exc}", file=sys.stderr)
        return 2
    except OSError as exc:
        detail = exc.strerror or str(exc)
        target = f": {exc.filename}" if exc.filename else ""
        print(f"{PROG}: error: {detail}{target}", file=sys.stderr)
        return 2


def _cmd_check(args: argparse.Namespace) -> int:
    env = load_env(args.env)
    schema = load_schema(args.schema)
    report = check(env, schema, allow_extra=args.allow_extra)
    if args.json:
        _write(json.dumps(report.to_dict(), indent=2, ensure_ascii=False))
    else:
        _write(format_report(report, args.env, args.schema))
    return 1 if report.has_errors else 0


def _cmd_diff(args: argparse.Namespace) -> int:
    left = load_env(args.a)
    right = load_env(args.b)
    result = compare(left, right)
    if args.json:
        payload = {"a": args.a, "b": args.b}
        payload.update(result.to_dict())
        _write(json.dumps(payload, indent=2, ensure_ascii=False))
    else:
        _write(format_diff(result, args.a, args.b))
    return 0 if result.identical else 1


def _cmd_init(args: argparse.Namespace) -> int:
    env = load_env(args.env)
    schema = infer_schema(env)
    text = render_schema(schema, header=f"Generated by envfy {__version__} from {args.env}")
    output = Path(args.output)
    output.write_text(text, encoding="utf-8")
    _write(f"{_MARKS['ok']} wrote {len(schema)} field(s) to {output}")
    return 0


def format_report(report: Report, env_label: str, schema_label: str) -> str:
    """Render a :class:`~envfy.validator.Report` for humans."""

    lines: List[str] = [f"envfy check  {env_label} vs {schema_label}"]
    for issue in report.issues:
        mark = _MARKS.get(issue.level, "?")
        suffix = f" (line {issue.line})" if issue.line is not None else ""
        lines.append(f"{mark} {issue.key}{suffix}: {issue.message}")
    if not report.issues:
        lines.append("✓ nothing to check (the schema is empty)")
    lines.append("")
    if report.has_errors:
        lines.append(
            f"{_MARKS['error']} {len(report.errors)} error(s), "
            f"{len(report.warnings)} warning(s), {report.checked} key(s) checked"
        )
    else:
        lines.append(
            f"{_MARKS['ok']} all {report.checked} key(s) passed ({len(report.warnings)} warning(s))"
        )
    return "\n".join(lines)


def _write(text: str, stream=None) -> None:
    """Write text, falling back to ASCII markers on legacy terminal encodings."""

    target = stream if stream is not None else sys.stdout
    try:
        target.write(text + "\n")
    except UnicodeEncodeError:
        fallback = text
        for original, replacement in _ASCII_FALLBACK.items():
            fallback = fallback.replace(original, replacement)
        target.write(fallback + "\n")


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
